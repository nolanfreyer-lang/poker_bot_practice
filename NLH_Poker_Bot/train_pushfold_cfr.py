"""Solve heads-up push/fold with CFR, one solution per stack depth.

    python3 train_pushfold_cfr.py

Game: the small blind shoves or folds; the big blind calls or folds. Every one of
the 169 starting hands gets its own strategy, weighted by how many combos it has
and which cards block each other. Writes pushfold_tables.py. Needs numpy here,
but the bots only read the finished table, so nothing extra ships to Chipzen.
"""
import random
from multiprocessing import Pool

import numpy as np

from poker_core import hand_rank, ALL_CLASSES, RANKS

CLASSES = sorted(ALL_CLASSES)
DEPTHS = list(range(2, 16))         # stack in big blinds
SIMS = 1500
ITERATIONS = 20000


def combos(hc):
    r1, r2 = RANKS.index(hc[0]), RANKS.index(hc[1])
    if len(hc) == 2:
        return [(r1 * 4 + a, r1 * 4 + b) for a in range(4) for b in range(a + 1, 4)]
    if hc[2] == "s":
        return [(r1 * 4 + s, r2 * 4 + s) for s in range(4)]
    return [(r1 * 4 + a, r2 * 4 + b) for a in range(4) for b in range(4) if a != b]


def matchup(task):
    i, j = task
    rng = random.Random(i * 1000 + j)
    A, B = combos(CLASSES[i]), combos(CLASSES[j])
    pairs = [(a, b) for a in A for b in B if not set(a) & set(b)]
    if not pairs:
        return i, j, 0.5, 0
    total = 0.0
    for _ in range(SIMS):
        a, b = rng.choice(pairs)
        board = rng.sample([c for c in range(52) if c not in a and c not in b], 5)
        x, y = hand_rank(list(a) + board), hand_rank(list(b) + board)
        total += 1.0 if x > y else 0.5 if x == y else 0.0
    return i, j, total / SIMS, len(pairs)


def equity_matrix():
    n = len(CLASSES)
    with Pool() as pool:
        rows = pool.map(matchup, [(i, j) for i in range(n) for j in range(i, n)], chunksize=200)
    eq, w = np.zeros((n, n)), np.zeros((n, n))
    for i, j, e, c in rows:
        eq[i, j], eq[j, i] = e, 1 - e if i != j else 0.5
        w[i, j] = w[j, i] = c
    return eq, w


def solve(eq, w, depth):
    """CFR+ on the shove/fold game. Values are in big blinds for the small blind."""
    n = len(CLASSES)
    sb = 0.5
    shove_ev = w * 0.0
    call_value = (2 * eq - 1) * depth       # SB's result when called
    regret_s, regret_c = np.zeros((n, 2)), np.zeros((n, 2))
    avg_s, avg_c = np.zeros(n), np.zeros(n)
    weights = w.sum(1)
    for t in range(1, ITERATIONS + 1):
        s = np.where(regret_s.sum(1) > 0, regret_s[:, 1] / np.maximum(regret_s.sum(1), 1e-12), 0.5)
        c = np.where(regret_c.sum(1) > 0, regret_c[:, 1] / np.maximum(regret_c.sum(1), 1e-12), 0.5)
        # small blind: value of shoving each hand vs the BB's calling strategy
        ev_shove = (w * ((1 - c)[None, :] * 1.0 + c[None, :] * call_value)).sum(1) / weights
        ev_fold = -sb
        node = s * ev_shove + (1 - s) * ev_fold
        regret_s[:, 1] = np.maximum(regret_s[:, 1] + (ev_shove - node), 0)
        regret_s[:, 0] = np.maximum(regret_s[:, 0] + (ev_fold - node), 0)
        # big blind: value of calling each hand vs the SB's shoving range
        reach = w * s[:, None]
        ev_call = (reach * (-call_value)).sum(0)
        ev_bb_fold = reach.sum(0) * -1.0
        node_c = c * ev_call + (1 - c) * ev_bb_fold
        regret_c[:, 1] = np.maximum(regret_c[:, 1] + (ev_call - node_c), 0)
        regret_c[:, 0] = np.maximum(regret_c[:, 0] + (ev_bb_fold - node_c), 0)
        avg_s += t * s
        avg_c += t * c
    norm = ITERATIONS * (ITERATIONS + 1) / 2
    avg_s, avg_c = avg_s / norm, avg_c / norm
    # exploitability: how much each side could gain by best-responding
    ev_shove = (w * ((1 - avg_c)[None, :] + avg_c[None, :] * call_value)).sum(1) / weights
    br_sb = (weights * np.maximum(ev_shove, -sb)).sum() / weights.sum()
    reach = w * avg_s[:, None]
    br_bb = np.maximum((reach * (-call_value)).sum(0), -reach.sum(0)).sum()
    br_bb += ((w * (1 - avg_s)[:, None]).sum() * sb)
    br_bb /= w.sum()
    return avg_s, avg_c, br_sb + br_bb


def main():
    eq, w = equity_matrix()
    table = {}
    combos_of = np.array([len(combos(h)) for h in CLASSES])
    for d in DEPTHS:
        s, c, gap = solve(eq, w, d)
        table[d] = {"shove": {h: round(float(x), 3) for h, x in zip(CLASSES, s) if x > 0.005},
                    "call": {h: round(float(x), 3) for h, x in zip(CLASSES, c) if x > 0.005}}
        print(f"{d:>3} BB: shove {100 * (s * combos_of).sum() / 1326:5.1f}%  call {100 * (c * combos_of).sum() / 1326:5.1f}%"
              f"  exploitability {gap:.4f} BB per hand")
    with open("pushfold_tables.py", "w") as f:
        f.write('"""GENERATED by train_pushfold_cfr.py. Equilibrium strategies by stack depth."""\n')
        f.write(f"PUSHFOLD = {table!r}\n")


if __name__ == "__main__":
    main()
