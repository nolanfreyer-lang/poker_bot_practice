"""Bundle a bot into one plain-Python bot.py for the E[X] Showdown (e-x.club/poker).

    python3 build_ex.py                         # DEEP_THOUGHT_V7 -> ../ex_deep_thought_v7/bot.py
    python3 build_ex.py --bot DEEP_THOUGHT_V6

E[X] takes a single bot.py exposing decide(game_state) -> dict, run under Python 3.10
with no network, no file writes, 2 s per action and 0.5 CPU (engine source:
github.com/uzlez/fullhouse-engine). This reuses build_chipzen.py's module merge and
appends the E[X] adapter below instead of the Chipzen one. No saved opponent profiles
are shipped: the field is new, so every read starts from scratch each match. Chips are
scored linearly (chip delta), so ICM stays off. Rerun after any strategy change; never
edit the generated bot.py by hand.
"""
