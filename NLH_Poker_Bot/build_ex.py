ADAPTER = r'''
# =====================================================================
# E[X] Showdown adapter
# =====================================================================
BOT_NAME = "@NAME@"
EX_OVERRIDES = {"USE_ICM": False}      # chip delta is scored linearly
EX_SMALL_BLIND, EX_BIG_BLIND = 50, 100
_BIG = 10 ** 12
_STREET_NAMES = ("preflop", "flop", "turn", "river")


class _Replay:
    """The engine's betting rules (engine/game.py), replayed over action_log.

    action_log has no street markers, so this tells which street each action was on and
    turns it into our history: (street, seat, kind, that player's street total)."""

    def __init__(self, n, stacks, big_blind):
        self.n, self.bb = n, big_blind
        self.stack = list(stacks)
        self.bet = [0] * n
        self.folded = [False] * n
        self.all_in = [False] * n
        self.street, self.current = 0, 0
        self.min_raise = self.last_agg = big_blind
        self.needs = set()
        self.done = False
        self.history = []
        self.paid = [0] * n             # chips each seat has put in this hand
        self.street_paid = [0] * n      # ... before the current street
        self.acted_on = [0] * n         # street of each seat's last action

    def active(self, i):
        return not self.folded[i] and not self.all_in[i] and self.stack[i] > 0

    def _put(self, i, amount):
        amount = max(0, min(amount, self.stack[i]))
        self.stack[i] -= amount
        self.bet[i] += amount
        self.paid[i] += amount
        self.current = max(self.current, self.bet[i])

    def blind(self, seat, amount, now_all_in=False):
        self._put(seat, amount)
        if self.stack[seat] == 0 or now_all_in:
            self.all_in[seat] = True
        self.history.append(("preflop", seat, "blind", self.bet[seat]))

    def start(self):
        self.min_raise = self.last_agg = self.bb
        self.needs = {i for i in range(self.n) if self.active(i)}

    def validate(self, seat, action, amount):
        """The engine's _validate: what a raw bot answer becomes."""
        act = str(action or "fold").lower().strip()
        try:
            amount = int(amount or 0)
        except (TypeError, ValueError):
            amount = 0
        if act not in ("check", "call", "raise", "all_in"):
            return "fold", 0
        owed = self.current - self.bet[seat]
        if act in ("check", "call"):
            return ("check", 0) if owed == 0 else ("call", owed)
        if act == "raise":
            amount = max(amount, self.current + self.min_raise)
            if amount - self.bet[seat] >= self.stack[seat]:
                return "all_in", self.stack[seat] + self.bet[seat]
            return "raise", amount
        return "all_in", self.stack[seat] + self.bet[seat]

    def _aggression(self, seat, size):
        if size >= self.last_agg:
            self.last_agg = self.min_raise = size
            self.needs = {i for i in range(self.n) if self.active(i) and i != seat}

    def apply(self, seat, act, amount, now_all_in=False):
        """One logged (already validated) action. now_all_in: the seat is all-in now and this
        is its last action, which matters when its stack isn't known exactly."""
        if self.done:
            return
        street = _STREET_NAMES[self.street]
        self.acted_on[seat] = self.street
        self.needs.discard(seat)
        prev = self.current
        if act == "fold":
            self.folded[seat] = True
            kind = "fold"
        elif act == "check":
            kind = "check"
        elif act == "call":
            self._put(seat, amount)
            kind = "call"
        elif act == "raise":
            self._put(seat, amount - self.bet[seat])
            kind = "raise"
        else:                                           # all_in: amount is the street total
            self._put(seat, amount - self.bet[seat] if amount else self.stack[seat])
            self.all_in[seat] = True
            kind = "allin" if self.bet[seat] > prev else "call"
        if self.stack[seat] == 0 or now_all_in:
            self.all_in[seat] = act != "fold" or self.all_in[seat]
        if kind == "raise":
            kind = "allin" if self.all_in[seat] else "bet" if prev == 0 else "raise"
        if kind in ("raise", "bet", "allin"):
            self._aggression(seat, self.current - prev)
        self.history.append((street, seat, kind, self.bet[seat]))
        if sum(1 for f in self.folded if not f) == 1:
            self.done = True
        elif not any(self.active(i) for i in self.needs):
            self._next_street()

    def _next_street(self):
        self.bet = [0] * self.n
        self.current = 0
        self.min_raise = self.last_agg = self.bb
        self.street += 1
        self.street_paid = list(self.paid)
        live = [i for i in range(self.n) if self.active(i)]
        if self.street > 3 or not live:
            self.done = True
            return
        self.needs = set(live)

    def street_name(self):
        return _STREET_NAMES[min(self.street, 3)]


def _hand_number(hand_id, fallback):
    tail = str(hand_id or "").rsplit("_h", 1)
    return int(tail[1]) if len(tail) == 2 and tail[1].isdigit() else fallback


class ExDeepThought:
    """decide(game_state) for E[X]: one per bot process, so reads last the whole match."""

    def __init__(self):
        self.core = @CORE@(overrides=EX_OVERRIDES)
        self.order = []             # bot_ids in seat order: our stable seat numbers
        self.hand = None            # (hand number, replay, seats seen in its log, seat map, my seat, board)
        self.starts = (None, {})    # (hand number, bot_id -> exact stack at the hand's start)
        self.errors = 0

    # ---------------------------------------------------------------- seats
    def seat_map(self, players):
        ids = [p["bot_id"] for p in players]
        self.order += [b for b in ids if b not in self.order]     # busted bots keep their number
        return {p["seat"]: self.order.index(p["bot_id"]) for p in players}

    # ---------------------------------------------------------------- replay
    def replay(self, state):
        """-> (replay with exact stacks, sb seat, bb seat) over this hand's action_log, or None."""
        players = sorted(state.get("players") or [], key=lambda p: p["seat"])
        log = state.get("action_log") or []
        n = len(players)
        blinds = {e["action"]: e for e in log if e.get("action") in ("small_blind", "big_blind")}
        if n < 2 or "big_blind" not in blinds:
            return None
        sb = blinds.get("small_blind", {}).get("seat")
        bb = blinds["big_blind"]["seat"]
        big = max(EX_BIG_BLIND, int(blinds["big_blind"].get("amount") or 0))
        now_all_in = {p["seat"] for p in players if p.get("is_all_in")}
        last = {}
        for k, e in enumerate(log):
            last[e["seat"]] = k

        def run(stacks):
            r = _Replay(n, stacks, big)
            for k, e in enumerate(log):
                forced = e["seat"] in now_all_in and last[e["seat"]] == k
                if e["action"] in ("small_blind", "big_blind"):
                    r.blind(e["seat"], int(e.get("amount") or 0), forced)
                    if e["action"] == "big_blind":
                        r.start()
                else:
                    r.apply(e["seat"], e["action"], int(e.get("amount") or 0), forced)
            return r

        # first pass with deep stacks gives what each seat has put in, so stacks at the start
        rough = run([_BIG] * n)
        start = [p["stack"] + rough.paid[i] for i, p in enumerate(players)]
        # an all-in call for less is logged as the full amount owed: on this street the seat's
        # bet says what it really put in, and for one earlier call the pot does
        short = [i for i in now_all_in if 0 <= i < n and log[last[i]]["action"] == "call"]
        number = _hand_number(state.get("hand_id"), None)
        known = self.starts[1] if self.starts[0] == number else {}
        unknown = []
        for i in short:
            if rough.acted_on[i] == rough.street:
                start[i] = rough.street_paid[i] + int(players[i].get("bet_this_street") or 0)
            elif players[i]["bot_id"] in known:     # seen exactly at an earlier decision this hand
                start[i] = known[players[i]["bot_id"]]
            else:
                unknown.append(i)
        if len(unknown) == 1:
            i = unknown[0]
            start[i] = max(0, int(state.get("pot") or 0) - sum(start[j] - players[j]["stack"]
                                                               for j in range(n) if j != i))
            unknown = []
        self.starts = (number, {**known, **{p["bot_id"]: start[i] for i, p in enumerate(players)
                                            if i not in unknown}})
        return run(start), sb, bb

    # ---------------------------------------------------------------- hand end
    def finish_hand(self, state):
        """Feed the last hand to the reads, finished from match_action_log."""
        number, r, seen, vseat, me, board = self.hand
        self.hand = None
        entries = [e for e in state.get("match_action_log") or [] if e.get("hand_num") == number]
        if len(entries) >= seen:
            for e in entries[seen:]:
                if r.done:
                    break
                seat = e.get("seat")
                if seat is None or not 0 <= seat < r.n:
                    break
                act, amount = r.validate(seat, e.get("action"), e.get("amount"))
                r.apply(seat, act, amount)
        history = [(st, vseat[seat], kind, amt) for st, seat, kind, amt in r.history]
        self.core.on_hand_end(history, sorted(vseat.values()), showdown=None, board=board, my_seat=me)

    # ---------------------------------------------------------------- decide
    def game_state(self, state):
        players = sorted(state["players"], key=lambda p: p["seat"])
        vseat = self.seat_map(players)
        me = vseat[state["seat_to_act"]]
        number = _hand_number(state.get("hand_id"), (self.hand or (0,))[0])
        if self.hand is not None and self.hand[0] != number:
            try:
                self.finish_hand(state)
            except Exception:
                self.hand = None
        found = self.replay(state)
        history, button, sb_amt, bb_amt = [], None, EX_SMALL_BLIND, EX_BIG_BLIND
        board = parse_cards(state.get("community_cards") or [])
        if found is not None:
            r, sb, bb = found
            if r.street_name() == state.get("street"):
                history = [(st, vseat[seat], kind, amt) for st, seat, kind, amt in r.history]
            n = len(players)
            dealer = sb if n == 2 else ((sb if sb is not None else bb - 1) - 1) % n
            button = vseat.get(dealer % n)
            log = state.get("action_log") or []
            sb_amt = max([EX_SMALL_BLIND] + [int(e.get("amount") or 0) for e in log if e.get("action") == "small_blind"])
            bb_amt = max([EX_BIG_BLIND] + [int(e.get("amount") or 0) for e in log if e.get("action") == "big_blind"])
            seen = sum(1 for e in log if e.get("action") not in ("small_blind", "big_blind"))
            self.hand = (number, r, seen, vseat, me, board)
        by_v = {vseat[p["seat"]]: p for p in players}
        infos = []
        for v in range(len(self.order)):
            p = by_v.get(v)
            if p is None:
                infos.append(PlayerInfo(seat=v, stack=0, bet=0, active=False, all_in=False, dealt=False))
            else:
                infos.append(PlayerInfo(seat=v, stack=int(p["stack"]), bet=int(p.get("bet_this_street") or 0),
                                        active=not p.get("is_folded"), all_in=bool(p.get("is_all_in")),
                                        dealt=True))
        if button is None:
            button = me
        stack = int(state["your_stack"])
        my_bet = int(state.get("your_bet_this_street") or 0)
        max_to = stack + my_bet
        return GameState(
            my_seat=me, hole_cards=parse_cards(state["your_cards"]), board=board,
            street=state["street"], pot=int(state["pot"]), players=infos, button_seat=button,
            small_blind=sb_amt, big_blind=bb_amt, to_call=min(int(state.get("amount_owed") or 0), stack),
            min_raise_to=min(int(state.get("min_raise_to") or max_to), max_to), max_raise_to=max_to,
            history=history, hand_number=number)

    @staticmethod
    def to_ex(a, state):
        can_check = bool(state.get("can_check")) or not state.get("amount_owed")
        if a.kind in ("fold", "check"):
            return {"action": "check"} if can_check else {"action": "fold"}
        if a.kind == "call":
            return {"action": "check"} if can_check else {"action": "call"}
        owed, stack = int(state.get("amount_owed") or 0), int(state["your_stack"])
        if a.kind == "allin" or int(a.amount) - int(state.get("your_bet_this_street") or 0) >= stack:
            return {"action": "call"} if owed >= stack else {"action": "all_in"}
        return {"action": "raise", "amount": int(a.amount)}

    def decide(self, state):
        if state.get("type") == "warmup":
            return {"action": "check"}
        try:
            return self.to_ex(self.core.act(self.game_state(state)), state)
        except Exception as e:      # a crash folds the hand; checking is never worse
            self.errors += 1
            if self.errors <= 3:
                print(f"decide error: {e!r}", file=sys.stderr)
            return {"action": "check"} if state.get("can_check") else {"action": "fold"}


_BOT = ExDeepThought()


def decide(game_state: dict) -> dict:
    return _BOT.decide(game_state)
'''

FORBIDDEN = {"socket", "urllib", "urllib2", "urllib3", "requests", "httpx", "aiohttp", "http", "ftplib",
             "smtplib", "telnetlib", "xmlrpc", "subprocess", "multiprocessing", "pickle", "shelve",
             "threading", "asyncio", "ctypes", "runpy", "importlib"}


def bundle(name):
    extra, core, _, _ = bc.BOTS[name]
    imports = {"import os", "import sys"}
    bodies = [bc.config_class()]
    for module in bc.COMMON + extra:
        mod_imports, body = bc.split_module(module)
        imports.update(mod_imports)
        bodies.append(f"# ---- {module}.py ----\n{body}")
    equity = json.dumps(json.loads((HERE / "preflop_equity.json").read_text()), separators=(",", ":"), sort_keys=True)
    text = (HEADER + "\n".join(sorted(imports)) + "\n\n" + bodies[0]
            + "\n\n_PREFLOP_TABLE = " + equity + "\n\n" + "\n\n".join(bodies[1:]) + "\n" + ADAPTER)
    text = text.replace("_updated._PREFLOP_TABLE", "_PREFLOP_TABLE").replace("@NAME@", name).replace("@CORE@", core)
    check(text)
    return text


def check(text):
    """The site's rules: Python 3.10 syntax, no banned imports or calls, under 5 MB."""
    tree = ast.parse(text, feature_version=(3, 10))
    for node in ast.walk(tree):
        names = []
        if isinstance(node, ast.Import):
            names = [a.name.split(".")[0] for a in node.names]
        elif isinstance(node, ast.ImportFrom) and node.module:
            names = [node.module.split(".")[0]]
        bad = set(names) & FORBIDDEN
        if bad:
            raise SystemExit(f"banned import {bad} at line {node.lineno}")
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and \
                node.func.id in ("__import__", "eval", "exec", "compile"):
            raise SystemExit(f"banned call {node.func.id}() at line {node.lineno}")
    if len(text.encode()) > 5 * 1024 * 1024:
        raise SystemExit("bot.py is over the 5 MB limit")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bot", type=str.upper, choices=list(bc.BOTS), default="DEEP_THOUGHT_V7")
    ap.add_argument("--out", help="output folder (default: ex_<bot> next to NLH_Poker_Bot)")
    args = ap.parse_args()
    out = Path(args.out) if args.out else HERE.parent / ("ex_" + args.bot.lower())
    out.mkdir(parents=True, exist_ok=True)
    (out / "bot.py").write_text(bundle(args.bot))
    print(f"wrote {out / 'bot.py'} ({(out / 'bot.py').stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
