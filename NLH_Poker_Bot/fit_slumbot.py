"""Measure how Slumbot really plays each kind of hand, from logged matches.

    python3 fit_slumbot.py

Slumbot reveals its cards on every hand, even folded ones, so its response to each
bet can be counted by hand strength and bet size. Writes fitted_tables.py, used as
DEEP_THOUGHT_V1's starting model for any opponent; live tracking adjusts from there.
"""
import glob
import json
import re
from collections import defaultdict

from poker_core import classify_hand, parse_cards
from slumbot_test import build_state, SLUMBOT

BUCKETS = ("MONSTER", "STRONG", "MEDIUM", "STRONG_DRAW", "DRAW", "WEAK")
SIZE_BINS = (0.4, 0.8, 1.2)        # bet as a share of the pot: small, medium, big, overbet
SMOOTH = 4                         # counts added per cell, pulled toward the bucket average
BOARD_LEN = {"flop": 3, "turn": 4, "river": 5}


def size_bin(frac):
    return next((i for i, x in enumerate(SIZE_BINS) if frac <= x), len(SIZE_BINS))


def collect(paths):
    open_counts = defaultdict(lambda: [0, 0])       # bucket -> [checks, bets]
    respond = defaultdict(lambda: [0, 0, 0])        # (bucket, size bin) -> [fold, call, raise]
    hands = 0
    for path in paths:
        for line in open(path):
            h = json.loads(line)
            if not h.get("bot_hole_cards"):
                continue
            hands += 1
            theirs = parse_cards(h["bot_hole_cards"])
            action, prefix, i = h["action"], "", 0
            for tok in re.findall(r"b\d+|[kcf/]", action):
                if tok == "/":
                    prefix += tok
                    continue
                state, actor = build_state(prefix, h["client_pos"], h["hole_cards"], [])
                street = state.street
                if actor == SLUMBOT and street != "preflop" and len(h["board"]) >= BOARD_LEN[street]:
                    bucket = classify_hand(theirs, parse_cards(h["board"][:BOARD_LEN[street]]), 8)
                    me, them = state.players[0], state.players[1]
                    to_call = me.bet - them.bet
                    if to_call <= 0:
                        open_counts[bucket][1 if tok[0] == "b" else 0] += 1
                    else:
                        pot_before = state.pot - to_call
                        cell = respond[(bucket, size_bin(to_call / max(1, pot_before)))]
                        cell[{"f": 0, "c": 1, "b": 2}[tok[0]]] += 1
                prefix += tok
    return hands, open_counts, respond


def main():
    hands, open_counts, respond = collect(sorted(glob.glob("slumbot_logs/*.jsonl")))
    if not hands:
        raise SystemExit("No hands found: run this from NLH_Poker_Bot. fitted_tables.py was not changed.")
    likely_bet = {}
    for b in BUCKETS:
        checks, bets = open_counts[b]
        likely_bet[b] = round((bets + 1) / (checks + bets + 2), 3)
    likely_check = {b: round(1 - likely_bet[b], 3) for b in BUCKETS}
    table = {}
    print(f"{hands} hands. Share betting when checked to, then fold/call/raise by bet size:")
    for b in BUCKETS:
        total = [sum(respond[(b, s)][k] for s in range(4)) for k in range(3)]
        n_all = sum(total) or 1
        avg = [(t + 1) / (n_all + 3) for t in total]
        table[b] = []
        row = []
        for s in range(4):
            cell = respond[(b, s)]
            n = sum(cell)
            probs = [round((cell[k] + SMOOTH * avg[k]) / (n + SMOOTH), 3) for k in range(3)]
            table[b].append(probs)
            row.append(f"{probs[0]:.2f}/{probs[1]:.2f}/{probs[2]:.2f} ({n})")
        print(f"  {b:<12} bets {likely_bet[b]:.2f} ({sum(open_counts[b])})  " + "  ".join(row))
    with open("fitted_tables.py", "w") as f:
        f.write('"""GENERATED by fit_slumbot.py from slumbot_logs/. Do not edit."""\n')
        f.write(f"SIZE_BINS = {SIZE_BINS!r}\nFIT_HANDS = {hands}\n")
        f.write(f"FIT_BET = {likely_bet!r}\nFIT_CHECK = {likely_check!r}\n")
        f.write(f"# bucket -> per size bin: [fold, call, raise]\nFIT_RESPONSE = {table!r}\n")
    print("wrote fitted_tables.py")


if __name__ == "__main__":
    main()
