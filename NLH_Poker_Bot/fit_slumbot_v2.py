"""Measure Slumbot's responses by street, hand strength and bet size, for DEEP_THOUGHT_V2.

    python3 fit_slumbot_v2.py

Unlike fit_slumbot.py, each street has its own table, because Slumbot's river calls
are far stronger than its flop calls. Fold rates are forced to rise with bet size,
so a bigger bet always costs something. Writes fitted_tables_v2.py.
"""
import glob
import json
import re
from collections import defaultdict

from poker_core import classify_hand, parse_cards
from slumbot_test import build_state, SLUMBOT

BUCKETS = ("MONSTER", "STRONG", "MEDIUM", "STRONG_DRAW", "DRAW", "WEAK")
STREETS = ("flop", "turn", "river")
SIZE_EDGES = (0.5, 0.8, 1.25, 2.0)          # bet as a share of the pot
SIZE_POINTS = (0.33, 0.66, 1.0, 1.5, 2.5)   # the size each bin stands for
SMOOTH = 8                                  # counts added per cell, pulled toward the street average
BOARD_LEN = {"flop": 3, "turn": 4, "river": 5}


def size_bin(frac):
    return next((i for i, x in enumerate(SIZE_EDGES) if frac <= x), len(SIZE_EDGES))


def collect(paths):
    respond = defaultdict(lambda: [0, 0, 0])        # (street, bucket, size bin) -> [fold, call, raise]
    hands = 0
    for path in paths:
        for line in open(path):
            h = json.loads(line)
            if not h.get("bot_hole_cards"):
                continue
            hands += 1
            theirs = parse_cards(h["bot_hole_cards"])
            prefix = ""
            for tok in re.findall(r"b\d+|[kcf/]", h["action"]):
                if tok == "/":
                    prefix += tok
                    continue
                state, actor = build_state(prefix, h["client_pos"], h["hole_cards"], [])
                street = state.street
                if actor == SLUMBOT and street != "preflop" and len(h["board"]) >= BOARD_LEN[street]:
                    me, them = state.players[0], state.players[1]
                    to_call = me.bet - them.bet
                    if to_call > 0:
                        bucket = classify_hand(theirs, parse_cards(h["board"][:BOARD_LEN[street]]), 8)
                        frac = to_call / max(1, state.pot - to_call)
                        respond[(street, bucket, size_bin(frac))][{"f": 0, "c": 1, "b": 2}[tok[0]]] += 1
                prefix += tok
    return hands, respond


def fit_row(cells):
    """Smoothed [fold, call, raise] per size, with folds never falling as bets grow."""
    total = [sum(cell[k] for cell in cells) for k in range(3)]
    n_all = sum(total)
    avg = [(t + 1) / (n_all + 3) for t in total]
    row, floor = [], 0.0
    for cell in cells:
        n = sum(cell)
        p = [(cell[k] + SMOOTH * avg[k]) / (n + SMOOTH) for k in range(3)]
        fold = max(p[0], floor)
        floor = fold
        rest = (1 - fold) / max(1e-9, p[1] + p[2])
        row.append([round(fold, 3), round(p[1] * rest, 3), round(p[2] * rest, 3)])
    return row


def main():
    hands, respond = collect(sorted(glob.glob("slumbot_logs/*.jsonl")))
    if not hands:
        raise SystemExit("No hands found: run this from NLH_Poker_Bot. fitted_tables_v2.py was not changed.")
    table = {}
    print(f"{hands} hands. Fold rate at each size (responses counted):")
    for street in STREETS:
        table[street] = {}
        for b in BUCKETS:
            cells = [respond[(street, b, i)] for i in range(len(SIZE_POINTS))]
            table[street][b] = fit_row(cells)
            shown = "  ".join(f"{r[0]:.2f} ({sum(c)})" for r, c in zip(table[street][b], cells))
            print(f"  {street:<6}{b:<12} {shown}")
    with open("fitted_tables_v2.py", "w") as f:
        f.write('"""GENERATED by fit_slumbot_v2.py from slumbot_logs/. Do not edit."""\n')
        f.write(f"SIZE_POINTS = {SIZE_POINTS!r}\nFIT_HANDS = {hands}\n")
        f.write(f"# street -> bucket -> per size point: [fold, call, raise]\nFIT_RESPONSE_V2 = {table!r}\n")
    print("wrote fitted_tables_v2.py")


if __name__ == "__main__":
    main()
